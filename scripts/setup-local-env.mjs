#!/usr/bin/env node
/**
 * Vytvorí/aktualizuje .env z .env.example + .deploy-secrets.
 * Lokálna DATABASE_URL synchronizuje aj do .env.local (Next.js ju má prednosť).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const examplePath = join(root, ".env.example");
const secretsPath = join(root, ".deploy-secrets");
const envPath = join(root, ".env");
const envLocalPath = join(root, ".env.local");

const LOCAL_DATABASE_URL =
  "postgresql://user:password@localhost:5433/bazos_monitor?schema=public";

if (!existsSync(examplePath)) {
  console.error("Missing .env.example");
  process.exit(1);
}

function parseEnvFile(content) {
  const vars = new Map();
  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    vars.set(key, value);
  }
  return vars;
}

function upsertEnvVar(filePath, key, value) {
  if (!existsSync(filePath)) {
    writeFileSync(filePath, `${key}="${value}"\n`, { mode: 0o600 });
    return;
  }

  let contents = readFileSync(filePath, "utf8");
  const line = `${key}="${value}"`;
  const pattern = new RegExp(`^${key}=.*$`, "m");

  if (pattern.test(contents)) {
    contents = contents.replace(pattern, line);
  } else {
    contents += `${contents.endsWith("\n") || contents.length === 0 ? "" : "\n"}${line}\n`;
  }

  writeFileSync(filePath, contents, { mode: 0o600 });
}

const exampleVars = parseEnvFile(readFileSync(examplePath, "utf8"));
const secretVars = existsSync(secretsPath)
  ? parseEnvFile(readFileSync(secretsPath, "utf8"))
  : new Map();

const merged = new Map(exampleVars);

for (const [key, value] of secretVars) {
  if (key === "DATABASE_URL") continue;
  if (value) merged.set(key, value);
}

merged.set(
  "DATABASE_URL",
  exampleVars.get("DATABASE_URL") ?? LOCAL_DATABASE_URL
);

const lines = [
  "# Auto-generated by scripts/setup-local-env.mjs — uprav DATABASE_URL podľa potreby",
  "",
  `DATABASE_URL="${merged.get("DATABASE_URL")}"`,
  `CRON_SECRET="${merged.get("CRON_SECRET") ?? ""}"`,
  `NEXT_PUBLIC_VAPID_PUBLIC_KEY="${merged.get("NEXT_PUBLIC_VAPID_PUBLIC_KEY") ?? ""}"`,
  `VAPID_PRIVATE_KEY="${merged.get("VAPID_PRIVATE_KEY") ?? ""}"`,
  `VAPID_SUBJECT="${merged.get("VAPID_SUBJECT") ?? ""}"`,
  `NEXT_PUBLIC_WEBMCP_ORIGIN_TRIAL_TOKEN="${merged.get("NEXT_PUBLIC_WEBMCP_ORIGIN_TRIAL_TOKEN") ?? ""}"`,
  "",
];

writeFileSync(envPath, lines.join("\n"), { mode: 0o600 });
console.log(`Wrote ${envPath}`);

upsertEnvVar(envLocalPath, "DATABASE_URL", merged.get("DATABASE_URL"));
console.log(`Synced DATABASE_URL in ${envLocalPath}`);
